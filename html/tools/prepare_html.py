#!/usr/bin/env python3
"""Prepare the project for the lwarp HTML build (nothing in the chapters is modified).

LabOpt has no separate *.tikz files and no PDF pictures: all drawings are inline tikzpicture environments,
lwarp turns each of them into an SVG by itself. What the HTML class needs is cut out of the print class:
  _html/shared-tikz.tex       the section "Рисування" of LabBook.cls (tikz/pgfplots setup, pics lava, laser, plate, ...)
  _html/shared-mathmacros.tex html/mathmacros.tex (\\vect, \\Efield, ...; the same file feeds MathJax)
so a change of the print class reaches the HTML version automatically.
Usage:  python prepare_html.py [--shared]     (both do the same; --shared is kept for the build script)"""
import os
import re
import sys

PRINT_CLASS = 'LabBook.cls'
MATHMACROS = os.path.join('html', 'mathmacros.tex')


def class_banners(L):
    """[(title, index of the opening rule, index of the first content line)] for the banners
       %=====  /  %  /  %<tabs>Title  /  %  /  %====="""
    out, i = [], 0
    rule = re.compile(r'^%={20,}\s*$')
    while i < len(L) - 4:
        if rule.match(L[i]) and L[i + 1].strip() == '%' and L[i + 2].lstrip('%').strip() and L[i + 3].strip() == '%' and rule.match(L[i + 4]):
            out.append((L[i + 2].lstrip('%').strip(), i, i + 5)); i += 5
        else:
            i += 1
    return out


def build_shared(src=PRINT_CLASS, outdir='_html'):
    os.makedirs(outdir, exist_ok=True)
    if not os.path.exists(src):
        sys.exit('ERROR: %s not found' % src)
    L = open(src, 'rb').read().decode('utf-8', errors='surrogateescape').replace('\r\n', '\n').split('\n')
    bans = class_banners(L)
    tikz = None
    for n, (title, op, cs) in enumerate(bans):
        if title.startswith('Рисування'):
            end = bans[n + 1][1] if n + 1 < len(bans) else len(L)
            tikz = L[cs:end]
    if tikz is None:
        sys.exit('ERROR: the banner "Рисування" was not found in %s (anchor of build_shared in prepare_html.py)' % src)
    text = '%% Generated by prepare_html.py from %s (part "Рисування"). Do not edit: edit %s.\n' % (src, src) + '\n'.join(tikz).rstrip() + '\n'
    open(os.path.join(outdir, 'shared-tikz.tex'), 'wb').write(text.encode('utf-8', errors='surrogateescape'))
    mm = open(MATHMACROS, 'rb').read().decode('utf-8')
    open(os.path.join(outdir, 'shared-mathmacros.tex'), 'wb').write(mm.encode('utf-8'))
    print('  shared parts: tikz (%d lines of %s), mathmacros (%s)' % (len(tikz), src, MATHMACROS))


if __name__ == '__main__':
    build_shared()
